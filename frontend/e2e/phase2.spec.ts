import { test, expect } from '@playwright/test';
import { authenticate, mutate } from './helpers';

test('CSV upload, profiling, filters, SQL, history, one demo, and user isolation', async ({ page, browser }) => {
  await authenticate(page);
  await page.goto('/app/datasets');
  await page.getByLabel('Choose dataset file').setInputFiles({ name: 'orders.csv', mimeType: 'text/csv', buffer: Buffer.from('date,product,region,revenue\n2025-01-01,Monitor,West,100\n2025-01-02,Laptop,East,200\n2025-01-03,Monitor,West,50\n2025-01-04,Audio,North,\n') });
  await expect(page.getByRole('heading', { name: 'orders', exact: true })).toBeVisible();
  const datasetId = page.url().split('/').at(-1)!;
  await expect(page.locator('.q-kpi').first().locator('strong')).toHaveText('4');
  await page.getByRole('tab', { name: 'Schema & types' }).click();
  await expect(page.locator('.q-schema-row').filter({ hasText: 'revenue' })).toContainText('number');
  await page.getByRole('tab', { name: 'Quality & suggestions' }).click();
  await expect(page.getByText('revenue: 1 missing values.', { exact: false })).toBeVisible();
  await page.getByRole('tab', { name: 'Data preview' }).click();
  await page.getByLabel('Search data rows').fill('Monitor');
  await expect(page.locator('.q-table tbody tr')).toHaveCount(2);
  await page.getByRole('link', { name: 'Explore with SQL' }).click();
  await page.getByLabel('SQL query').fill('SELECT region, SUM(revenue) AS total FROM data GROUP BY region ORDER BY total DESC');
  await page.getByRole('button', { name: 'Run query', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Results, grounded in your data' })).toBeVisible();
  await expect(page.locator('.q-table')).toContainText('200');
  await expect(page.locator('.q-table')).toContainText('150');
  await page.getByLabel('Saved query name').fill('Regional revenue');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText('Query saved to your workspace.')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: /Regional revenue/ })).toBeVisible();
  const unsafe = await mutate(page.request, '/api/queries/run', { datasetId, sql: 'DELETE FROM data' });
  expect(unsafe.status()).toBe(400);
  const firstDemo = await mutate(page.request, '/api/datasets/demo');
  expect(firstDemo.status()).toBe(200);
  const demo = await firstDemo.json();
  expect(demo.rowCount).toBe(750);
  expect(demo.demo).toBe(true);
  expect((await (await mutate(page.request, '/api/datasets/demo')).json()).id).toBe(demo.id);
  const datasets = await (await page.request.get('/api/datasets')).json();
  expect(datasets.filter((d: { is_demo: boolean }) => d.is_demo)).toHaveLength(1);
  await page.goto(`/app/datasets/${demo.id}`);
  await page.screenshot({ path: 'artifacts/ecommerce-dataset.png', fullPage: true });
  const other = await browser.newContext({ baseURL: 'http://127.0.0.1:5173' });
  const otherPage = await other.newPage();
  await authenticate(otherPage);
  expect((await other.request.get(`/api/datasets/${datasetId}`)).status()).toBe(404);
  expect((await other.request.get(`/api/datasets/${datasetId}/rows`)).status()).toBe(404);
  expect((await mutate(other.request, '/api/queries/run', { datasetId, sql: 'SELECT * FROM data' })).status()).toBe(404);
  expect((await (await other.request.get('/api/queries')).json())).toEqual([]);
  await other.close();
});
