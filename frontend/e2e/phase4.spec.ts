import { test, expect } from '@playwright/test';
import { authenticate, mutate } from './helpers';

test('saved dashboards, chart customization, filters, presentation, CSV and PDF exports', async ({ page }) => {
  test.setTimeout(180_000);
  await authenticate(page);
  await mutate(page.request, '/api/datasets/demo');
  await page.goto('/app/dashboards');
  await page.getByLabel('Dashboard name', { exact: true }).fill('E-commerce pulse');
  await page.getByRole('button', { name: 'Create dashboard', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'E-commerce pulse', exact: true })).toBeVisible();
  await expect(page.locator('.q-kpi-result')).toHaveCount(2);
  await expect(page.locator('.q-builder-widget')).toHaveCount(5);
  await expect(page.locator('.q-widget-loading')).toHaveCount(0, { timeout: 45_000 });
  await page.getByLabel('Chart type for Monthly revenue').selectOption('line');
  await page.getByRole('button', { name: 'Move Total revenue down', exact: true }).click();
  await page.getByRole('button', { name: 'Save layout', exact: true }).click();
  await expect(page.getByText('Dashboard saved.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('.q-builder-widget').first().getByRole('heading')).toHaveText('Total profit');
  await expect(page.getByLabel('Chart type for Monthly revenue')).toHaveValue('line');
  await page.getByRole('button', { name: 'Present', exact: true }).click();
  await expect(page.locator('.q-sidebar')).toBeHidden();
  await page.getByRole('button', { name: 'Exit presentation', exact: true }).click();
  await page.getByLabel('Dashboard date from').fill('2025-06-01');
  await page.getByLabel('Dashboard date to').fill('2025-12-31');
  await expect(page.locator('.q-widget-loading')).toHaveCount(0, { timeout: 45_000 });
  await page.screenshot({ path: 'artifacts/dashboard-builder.png', fullPage: true });
  await page.goto('/app/reports');
  await page.getByLabel('Report title').fill('Regional revenue report');
  await page.getByLabel('Report SQL').fill('SELECT region, SUM(revenue) AS revenue FROM data GROUP BY region');
  await page.getByRole('button', { name: 'Preview report', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Regional revenue report' })).toBeVisible();
  const csv = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  expect((await csv).suggestedFilename()).toBe('Regional revenue report.csv');
  const pdf = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export PDF', exact: true }).click();
  expect((await pdf).suggestedFilename()).toBe('Regional revenue report.pdf');
  await page.screenshot({ path: 'artifacts/reports.png', fullPage: true });
});
